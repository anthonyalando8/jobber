package store

import (
	"context"
	"time"

	"github.com/jackc/pgx/v5"
)

// LegacyInventory is the read-only census of what the pre-v2 pipeline left behind. It exists so
// the transition can be reported honestly: nothing here deletes, rewrites or reclassifies a
// legacy row, and every category states what may still be done with it.
type LegacyInventory struct {
	CapturedAt    time.Time         `json:"captured_at"`
	SchemaVersion int               `json:"schema_version"`
	Categories    []LegacyCategory  `json:"categories"`
	Preservation  map[string]string `json:"preservation_digests"`
}

// LegacyCategory reports one class of legacy artifact. Disposition is the operative fact: what
// the system will and will not let this category do now.
type LegacyCategory struct {
	Name        string `json:"name"`
	Count       int    `json:"count"`
	Disposition string `json:"disposition"`
	Note        string `json:"note"`
}

// Dispositions. A legacy row is never deleted, so "removed" is deliberately not one of them.
const (
	DispositionPreserved         = "preserved"
	DispositionReadOnly          = "read_only"
	DispositionStaleBlocked      = "stale_blocked_from_v2"
	DispositionNeedsClassifying  = "needs_explicit_classification"
	DispositionActionableInV2    = "actionable_through_v2"
	DispositionMigratedReference = "migrated_reference_retained"
)

// LegacyInventoryReport counts what remains. Each query is deliberately explicit rather than
// generated, because the point of the report is that a reader can check the definition of every
// number against the schema.
func LegacyInventoryReport(ctx context.Context, conn *pgx.Conn) (*LegacyInventory, error) {
	inv := &LegacyInventory{CapturedAt: time.Now().UTC(), Preservation: map[string]string{}}
	if err := conn.QueryRow(ctx, `SELECT COALESCE(MAX(version),0) FROM schema_migrations`).Scan(&inv.SchemaVersion); err != nil {
		return nil, err
	}

	type probe struct {
		name, disposition, note, query string
	}
	// A draft belongs to v2 if and only if it has a draft_composition row. That is the
	// authoritative marker: it is a foreign key, not a text column that could disagree with
	// reality, and it is what the send path actually reads.
	probes := []probe{
		{
			"legacy_unsent_drafts", DispositionStaleBlocked,
			"Generated by the pre-v2 pipeline with no profile, opportunity, recipient or review context. Visible and readable; cannot be approved or sent. Contacting the company again requires a new v2 contact plan.",
			`SELECT count(*) FROM draft d WHERE NOT EXISTS(SELECT 1 FROM draft_composition c WHERE c.draft_id=d.id)
			   AND d.state NOT IN ('sent','discarded')`,
		},
		{
			"legacy_discarded_drafts", DispositionPreserved,
			"Discarded before v2. Retained exactly as written.",
			`SELECT count(*) FROM draft d WHERE NOT EXISTS(SELECT 1 FROM draft_composition c WHERE c.draft_id=d.id)
			   AND d.state='discarded'`,
		},
		{
			"legacy_sent_drafts", DispositionReadOnly,
			"Sent by the pre-v2 pipeline. Immutable history. Intent, profile revision and evidence are unknown and are reported as unknown rather than reconstructed.",
			`SELECT count(*) FROM draft d WHERE NOT EXISTS(SELECT 1 FROM draft_composition c WHERE c.draft_id=d.id)
			   AND d.state='sent'`,
		},
		{
			"legacy_send_log_threads", DispositionPreserved,
			"Historical outbound records, including follow-up schedule and reply/bounce timestamps. Never rewritten.",
			`SELECT count(*) FROM send_log`,
		},
		{
			"legacy_threads_unclassified", DispositionNeedsClassifying,
			"Sent threads with no recorded v2 intent. A v2 follow-up cannot be prepared for one of these until a person classifies it; intent is never inferred from company segment or the old application flag.",
			`SELECT count(*) FROM send_log s WHERE NOT EXISTS(SELECT 1 FROM legacy_thread_intent i WHERE i.send_log_id=s.id AND i.superseded_at IS NULL)`,
		},
		{
			"legacy_threads_classified_unknown", DispositionNeedsClassifying,
			"Explicitly classified as unknown by a person. Deliberately left legacy; no v2 follow-up is offered.",
			`SELECT count(*) FROM legacy_thread_intent WHERE intent='unknown' AND superseded_at IS NULL`,
		},
		{
			"legacy_threads_classified", DispositionMigratedReference,
			"A person determined the original intent. A v2 follow-up may be composed and reviewed normally; no old text or approval is carried over.",
			`SELECT count(*) FROM legacy_thread_intent WHERE intent<>'unknown' AND superseded_at IS NULL`,
		},
		{
			"legacy_followups_already_sent", DispositionPreserved,
			"Follow-ups sent by the pre-v2 scheduler. History only.",
			`SELECT count(*) FROM send_log WHERE followup_1_sent_at IS NOT NULL OR followup_2_sent_at IS NOT NULL`,
		},
		{
			"legacy_templates", DispositionReadOnly,
			"Pre-v2 message templates, including the payments-heavy ones. Retained for reference; they cannot drive v2 composition, which uses the versioned prompts under internal/composition/prompts.",
			`SELECT count(*) FROM template`,
		},
		{
			"legacy_detection_signals", DispositionMigratedReference,
			"Keyword detections from the old researcher. Readable and still cited by old drafts; they are labelled as detections and cannot serve as verbatim evidence for a v2 claim.",
			`SELECT count(*) FROM signal WHERE extraction_method='legacy_detection' OR extraction_method IS NULL OR extraction_method=''`,
		},
		{
			"companies_with_legacy_segment", DispositionReadOnly,
			"Companies still carrying the old hiring/application segment string. It is displayed as legacy context and can never select a v2 intent.",
			`SELECT count(*) FROM company WHERE segment IS NOT NULL AND segment<>''`,
		},
		{
			"suppression_rows", DispositionPreserved,
			"Do-not-contact records. Enforced at v2 send time exactly as before.",
			`SELECT count(*) FROM suppression`,
		},
		{
			"v2_compositions", DispositionActionableInV2,
			"Drafts created by the v2 pipeline, carrying a full snapshot, both validation layers and a review result.",
			`SELECT count(*) FROM draft_composition`,
		},
		{
			"v2_send_attempts", DispositionPreserved,
			"Permanent record of every v2 transmission attempt.",
			`SELECT count(*) FROM send_attempt`,
		},
	}

	for _, p := range probes {
		var count int
		if err := conn.QueryRow(ctx, p.query).Scan(&count); err != nil {
			return nil, err
		}
		inv.Categories = append(inv.Categories, LegacyCategory{
			Name: p.name, Count: count, Disposition: p.disposition, Note: p.note,
		})
	}

	// Content digests over historical outbound text. Re-running the inventory after any
	// transition and comparing these proves nothing rewrote what was actually sent.
	digests := map[string]string{
		"sent_draft_bodies":  `SELECT COALESCE(md5(string_agg(d.id||':'||md5(d.body),',' ORDER BY d.id)),'none') FROM draft d WHERE d.state='sent'`,
		"sent_draft_subject": `SELECT COALESCE(md5(string_agg(d.id||':'||md5(COALESCE(d.subject,'')),',' ORDER BY d.id)),'none') FROM draft d WHERE d.state='sent'`,
		"send_log_rows":      `SELECT COALESCE(md5(string_agg(id||':'||to_value||':'||sent_at::text,',' ORDER BY id)),'none') FROM send_log`,
		"template_bodies":    `SELECT COALESCE(md5(string_agg(id||':'||md5(body),',' ORDER BY id)),'none') FROM template`,
		"suppression_rows":   `SELECT COALESCE(md5(string_agg(value||':'||created_at::text,',' ORDER BY value)),'none') FROM suppression`,
		"contact_rows":       `SELECT COALESCE(md5(string_agg(id||':'||value,',' ORDER BY id)),'none') FROM contact`,
		"company_rows":       `SELECT COALESCE(md5(string_agg(id||':'||name,',' ORDER BY id)),'none') FROM company`,
	}
	for name, query := range digests {
		var digest string
		if err := conn.QueryRow(ctx, query).Scan(&digest); err != nil {
			return nil, err
		}
		inv.Preservation[name] = digest
	}
	return inv, nil
}
